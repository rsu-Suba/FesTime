import JSZip from "jszip";
import { EventConfig, StudioLayoutConfig, StudioState, EnvConfig } from "@/types/studio";

export function generateCustomConfigFile(config: EventConfig, layout?: StudioLayoutConfig): string {
  const customConfigObject = JSON.parse(JSON.stringify(config));
  if (layout) {
    customConfigObject.navigation.tabs = layout.user.mobileTabs.map(t => ({
      id: t.id,
      label: t.title,
      icon: t.icon || "MoreHorizRounded"
    }));
  }

  customConfigObject.external = {
    gaId: "__GA_ID_PROCESS_ENV__",
  };

  if (!customConfigObject.bus) {
    customConfigObject.bus = {
      defaultFromStop: "キャンパス 発",
      defaultToStop: "中央駅 着",
      routeLabels: {
        Outbound: { ja: "キャンパス 行", en: "To Campus" },
        Inbound: { ja: "中央駅 行", en: "To Central Station" },
      },
      stopTranslations: {
        "キャンパス 発": { ja: "キャンパス 発", en: "Campus (Dep.)" },
        "キャンパス 着": { ja: "キャンパス 着", en: "Campus (Arr.)" },
        "北駅 発": { ja: "北駅 発", en: "North St. (Dep.)" },
        "北駅 着": { ja: "北駅 着", en: "North St. (Arr.)" },
        "中央駅 発": { ja: "中央駅 発", en: "Central St. (Dep.)" },
        "中央駅 着": { ja: "中央駅 着", en: "Central St. (Arr.)" },
      },
    };
  }

  let serializedConfig = JSON.stringify(customConfigObject, null, 2);
  serializedConfig = serializedConfig.replace('"__GA_ID_PROCESS_ENV__"', 'process.env.NEXT_PUBLIC_GOOGLE_ANALYTICS_ID');

  return `
// Auto generated by FesTime Studio

export interface EventConfig {
  identity: {
    eventName: string;
    organizationName: string;
    appTitle: string;
    appDescription: string;
    eventStartDate: string; // YYYY-MM-DD
    eventEndDate: string;   // YYYY-MM-DD
  };
  
  navigation: {
    homepageUrl: string;
    basePath: string;
    tabs?: {
      id: string;
      label: string;
      icon: string;
    }[];
  };
  
  theme: {
    primaryColor: { light: string; dark: string; };
    backgroundColor: { light: string; dark: string; };
    mainLogoPath: string;
  };
  
  api: {
    pollingIntervalMs: number;
    fullRefreshFrequency: number;
  };

  external: {
    gaId?: string;
  };

  features: {
    booth: boolean;
    vote: boolean;
    bus: boolean;
    qa: boolean;
    lost: boolean;
    exhibition: boolean;
    event: boolean;
    news: boolean;
    map: boolean;
    closedOverlay: boolean;
  };

  bus?: {
    defaultFromStop: string;
    defaultToStop: string;
    routeLabels: {
      [routeKey: string]: {
        ja: string;
        en: string;
      };
    };
    stopTranslations?: {
      [stopName: string]: {
        ja: string;
        en: string;
      };
    };
  };
}

export const CUSTOM_CONFIG: EventConfig = ${serializedConfig};
`;
}

export function generateLayoutUtilsFile(layout: StudioLayoutConfig): string {
  return `import React from "react";

export interface LayoutOptions {
  isMobile: boolean;
  columns: number;
  isStallAdmin: boolean;
  hasVotedBoth?: boolean;
}

export const calculateLayout = (cards: Record<string, React.ReactNode>, options: LayoutOptions) => {
  const { isMobile, columns, isStallAdmin } = options;

  if (isMobile) {
    return [
${layout.user.mobileTabs
  .map(
    (tab) =>
      `      [${tab.cards.map((c) => `cards.${c}`).join(", ")}], // ${tab.title}`
  )
  .join("\n")}
    ].filter((col) => col && col.length > 0);
  }

  if (columns === 4) {
    return [
${layout.user.pcColumns.col4
  .map((col) => `      [${col.map((c) => `cards.${c}`).join(", ")}],`)
  .join("\n")}
    ];
  }

  if (columns === 3) {
    return [
${layout.user.pcColumns.col3
  .map((col) => `      [${col.map((c) => `cards.${c}`).join(", ")}],`)
  .join("\n")}
    ];
  }

  return [
${layout.user.pcColumns.col2
  .map((col) => `    [${col.map((c) => `cards.${c}`).join(", ")}],`)
  .join("\n")}
  ];
};

export const calculateAdminLayout = (managers: Record<string, React.ReactNode>, options: { isMobile: boolean; columns?: number }) => {
  const { isMobile } = options;

  if (isMobile) {
    return [
${(layout.admin?.mobileTabs || [])
  .map(
    (tab) =>
      `      [${tab.cards.map((c) => `managers.${c}`).join(", ")}], // ${tab.title}`
  )
  .join("\n")}
      [managers.Settings], // 設定
    ].filter((col) => col && col.length > 0 && col[0] != null);
  }

  return [
${(layout.admin?.pcColumns || [["NewsManager"], ["QAManager"], ["LostManager"]])
  .map((col) => `    [${col.map((c) => `managers.${c}`).join(", ")}],`)
  .join("\n")}
  ].filter((col) => col && col.length > 0);
};

export const calculateStallAdminLayout = (managers: Record<string, React.ReactNode>, options: { isMobile: boolean; columns?: number }) => {
  const { isMobile } = options;

  if (isMobile) {
    return [
${(layout.stallAdmin?.mobileTabs || [])
  .map(
    (tab) =>
      `      [${tab.cards.map((c) => `managers.${c}`).join(", ")}], // ${tab.title}`
  )
  .join("\n")}
    ].filter((col) => col && col.length > 0 && col[0] != null);
  }

  return [
${(layout.stallAdmin?.pcColumns || [["BoothManager"], ["News"]])
  .map((col) => `    [${col.map((c) => `managers.${c}`).join(", ")}],`)
  .join("\n")}
  ].filter((col) => col && col.length > 0);
};
`;
}

